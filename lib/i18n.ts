const DICTS: Record<Lang, Record<DictKey, string>> = { en, es };

export type T = (key: DictKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = DICTS[lang] ?? en;
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

/** Picks the Spanish field when the site is in Spanish and a translation exists. */
export function pick<T extends Record<string, unknown>>(obj: T, field: keyof T & string, lang: Lang): string {
  const base = (obj[field] as string) ?? "";
  if (lang !== "es") return base;
  const es = obj[`${field}Es` as keyof T];
  return typeof es === "string" && es.trim() ? es : base;
}
